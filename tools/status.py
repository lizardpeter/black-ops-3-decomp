#!/usr/bin/env python3
"""Regenerate STATUS.md from analysis/ + records/. Never edit STATUS.md by hand.

    python3 tools/status.py
"""
from collections import Counter, defaultdict

from model import LADDER, ROOT, config, load


def bar(done, total, width=20):
    n = round(width * done / total) if total else 0
    return "█" * n + "░" * (width - n)


def main():
    cfg = config()
    out = ["# Status", "", "_Generated by `tools/status.py` from `analysis/` and `records/`. Do not edit._", ""]
    for b in cfg.get("build", []):
        fns = load(b["id"])
        if not fns:
            continue
        c = Counter(f.status for f in fns.values())
        total = len(fns)
        out += [f"## {b['id']}", "", "| status | functions | reached |", "|---|---:|---|"]
        for i, s in enumerate(LADDER):
            reached = sum(c[t] for t in LADDER[i:])
            out.append(f"| {s} | {c[s]:,} | {bar(reached, total)} {reached / total:.1%} |")
        out += ["", f"{total:,} functions known. Reconstructed (decompiled or better): "
                    f"{sum(c[t] for t in LADDER[3:]):,}.", ""]
        if b is cfg["build"][0]:
            subs = defaultdict(Counter)
            for f in fns.values():
                subs[f.subsystem][f.status] += 1
            out += ["### By subsystem (top 25 by size)", "", "| subsystem | functions | decompiled+ | matches+ |",
                    "|---|---:|---:|---:|"]
            for name, cc in sorted(subs.items(), key=lambda kv: -sum(kv[1].values()))[:25]:
                n = sum(cc.values())
                out.append(f"| `{name}` | {n:,} | {sum(cc[t] for t in LADDER[3:]):,} | "
                           f"{sum(cc[t] for t in LADDER[5:]):,} |")
            out.append("")
    (ROOT / "STATUS.md").write_text("\n".join(out))
    print("\n".join(out[:20]))


if __name__ == "__main__":
    main()
